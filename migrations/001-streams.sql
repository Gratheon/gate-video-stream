CREATE TABLE IF NOT EXISTS streams (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL,
  box_id INTEGER NOT NULL,
  max_segment INTEGER NOT NULL,
  start_time TIMESTAMPTZ DEFAULT NULL,
  end_time TIMESTAMPTZ DEFAULT NULL,
  last_upload_time TIMESTAMPTZ DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS segments (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL,
  stream_id INTEGER NOT NULL,
  chunk_id INTEGER DEFAULT NULL,
  add_time TIMESTAMPTZ DEFAULT NOW(),
  process_start_time TIMESTAMPTZ DEFAULT NULL,
  process_end_time TIMESTAMPTZ DEFAULT NULL,
  bees_in INTEGER DEFAULT NULL,
  bees_out INTEGER DEFAULT NULL,
  varroa_count INTEGER DEFAULT NULL,
  wespen_count INTEGER DEFAULT NULL,
  pollen_count INTEGER DEFAULT NULL
);
